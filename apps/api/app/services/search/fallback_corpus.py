def fallback_search_results(query: str, selected_sources: list[str], limit: int) -> list[PaperRecord]:
    query_terms = {
        term
        for term in re.findall(r"\b[\w-]+\b", query.lower())
        if len(term) > 2 and term not in _FALLBACK_STOPWORDS
    }
    specific_terms = query_terms - _GENERIC_RESEARCH_TERMS
    min_overlap = max(1, min(3, round(len(query_terms) * 0.5)))
    scored = []
    for paper in _fallback_corpus():
        if paper.paper_id.startswith("fallback-hinton") and not {"geoffrey", "hinton"} & query_terms:
            continue
        text_terms = set(re.findall(r"\b[\w-]+\b", f"{paper.title} {paper.abstract or ''}".lower()))
        overlap = len(query_terms & text_terms)
        specific_overlap = len(specific_terms & text_terms)
        if query_terms and (overlap < min_overlap or (specific_terms and specific_overlap == 0)):
            continue
        preferred_source = _match_source(paper, selected_sources)
        paper_copy = paper.model_copy(deep=True)
        paper_copy.source = preferred_source
        paper_copy.all_sources = sorted(set(paper.all_sources + [preferred_source]))
        scored.append((specific_overlap, overlap, paper_copy.citation_count, paper_copy))
    scored.sort(key=lambda item: (item[0], item[1], item[2]), reverse=True)
    return [paper for _, _, _, paper in scored[:limit]]


def _match_source(paper: PaperRecord, selected_sources: list[str]) -> str:
    for source in selected_sources:
        if source in paper.all_sources:
            return source
    return paper.source


