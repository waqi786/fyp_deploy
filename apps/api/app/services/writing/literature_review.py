class LiteratureReviewService:
    def __init__(self) -> None:
        self.provider = get_default_model_provider()
        self.critic = SelfCritiqueService()
        self.packager = WritingArtifactPackager()

    def generate(self, payload: LiteratureReviewRequest) -> LiteratureReviewResponse:
        generated_at = datetime.now(UTC).isoformat()
        outline = self._outline(payload)
        sections = self._sections(payload, outline)
        source_spans = self._source_spans(payload)
        section_details = self._section_details(payload, sections, source_spans, generated_at)
        standalone = self._standalone_generators(sections)
        paragraph_map = self._paragraph_citation_map(sections, source_spans)
        citation_previews = self._citation_style_previews(payload)
        reference_list = self._reference_list(payload)
        critique_input = " ".join(sections.values())
        critique = self.critic.critique(critique_input, source_spans)
        critique_trace = [
            ClaimTrace(
                sentence=entry["sentence"],
                verdict=entry["verdict"],
                matched_terms=list(entry["matched_terms"]),
                confidence_score=float(entry["confidence_score"]),
                source_span=list(entry["source_span"]),
                model_used=self.provider.provider_name,
                generated_at=generated_at,
            )
            for entry in self.critic.critique_trace(critique_input, source_spans)
        ]
        readability = self._readability(payload.extracted_text)
        grammar_notes = self._grammar_notes(payload.extracted_text)
        academic_style_corrections = self._academic_style_corrections(payload)
        transitions = self._transition_suggestions(sections)
        diversity_nudge = self._citation_diversity_nudge(payload.extracted_text)
        inserted_visuals = self._inserted_visuals(payload)
        figure_table_insertions = self._figure_table_insertions(payload)
        exports = self._exports(payload, sections)
        export_artifacts = self._export_artifacts(payload, exports, generated_at)
        cover_letter = self._cover_letter(payload)
        peer_review_response = self._peer_review_response(payload)
        version_history = self._version_history(payload)
        track_changes = self._track_changes(sections)
        plagiarism_report = self._plagiarism_report(payload, sections)
        word_count_report = self._word_count_report(payload, sections)
        section_regeneration = self._section_regeneration(payload, sections)
        rollback_preview = self._rollback_preview(payload, version_history)
        watermark = "AI-assisted draft generated by Resora." if payload.disclosure_watermark else None
        confidence_score = self._confidence_score(critique, payload, sections)
        return LiteratureReviewResponse(
            outline=outline,
            sections=sections if not payload.outline_only else {},
            section_details=[] if payload.outline_only else section_details,
            standalone_generators=standalone,
            target_style_adaptation=self._target_style_adaptation(payload),
            paragraph_citation_map=paragraph_map,
            citation_style_previews=citation_previews,
            reference_list=reference_list,
            self_critique=critique,
            critique_trace=critique_trace,
            plagiarism_report=plagiarism_report,
            readability_score=readability,
            grammar_notes=grammar_notes,
            academic_style_corrections=academic_style_corrections,
            transition_suggestions=transitions,
            citation_diversity_nudge=diversity_nudge,
            inserted_visuals=inserted_visuals,
            figure_table_insertions=figure_table_insertions,
            export_formats=exports,
            export_artifacts=export_artifacts,
            overleaf_export=exports["overleaf_latex"],
            word_count_report=word_count_report,
            section_regeneration=section_regeneration,
            cover_letter=cover_letter,
            peer_review_response=peer_review_response,
            version_history=version_history,
            rollback_preview=rollback_preview,
            track_changes=track_changes,
            coauthor_comments=payload.comments,
            watermark=watermark,
            confidence_score=confidence_score,
            source_spans=source_spans,
            model_used=self.provider.provider_name,
            generated_at=generated_at,
        )

    def _outline(self, payload: LiteratureReviewRequest) -> list[str]:
        base = [
            "Abstract",
            "Introduction",
            "Related Work",
            "Methodology Landscape",
            "Comparative Findings",
            "Datasets and Benchmarks",
            "Trust and Limitations",
            "Research Gaps",
            "Conclusion",
            "Future Directions",
        ]
        if payload.mode == "grant_proposal":
            base = ["Abstract", "Problem Statement", "Objectives", "Proposed Work", "Expected Impact", "Timeline", "Budget Narrative"]
        elif payload.mode == "thesis_chapter":
            base = ["Chapter Overview", "Background", "Detailed Review", "Synthesis", "Critical Gaps", "Chapter Summary"]
        if payload.section_only:
            return [payload.section_only]
        return base

    def _sections(self, payload: LiteratureReviewRequest, outline: list[str]) -> dict[str, str]:
        structured = self.provider.structured_sections(payload.title, payload.extracted_text)
        visual_line = " ".join([figure.caption for figure in payload.figures[:3]] + [table.caption for table in payload.tables[:2]])
        sections = {}
        for section in outline:
            lowered = section.lower()
            if "abstract" in lowered:
                body = structured["problem"]
            elif "introduction" in lowered or "background" in lowered:
                body = structured["problem"]
            elif "related" in lowered:
                body = structured["methodology"]
            elif "method" in lowered:
                body = structured["methodology"]
            elif "dataset" in lowered or "benchmark" in lowered:
                body = f"{structured['findings']} {visual_line}".strip()
            elif "gap" in lowered or "future" in lowered:
                body = structured["conclusion"] or structured["findings"]
            else:
                body = structured["findings"]
            if payload.target_style.lower() == "ieee":
                body = f"In IEEE tone, {body}"
            elif payload.target_style.lower() == "apa":
                body = f"In APA style, {body}"
            if payload.tone == "concise":
                body = body[:220]
            elif payload.tone == "formal":
                body = f"{body} This section maintains formal academic phrasing."
            if payload.language.lower() == "ur":
                body = self._urdu_review_section(section, body)
            target_words = payload.section_length_targets.get(section)
            if target_words:
                body = self._fit_word_target(body, target_words)
            sections[section] = body
        return sections

    def _urdu_review_section(self, section: str, body: str) -> str:
        label = URDU_HEADING_LABELS.get(section.lower(), section)
        return (
            f"{label}: یہ ادبی جائزہ فراہم کردہ مقالوں کے شواہد، طریقہ کار، نتائج، حدود، "
            f"اور تحقیقی خلا کو ایک مربوط انداز میں بیان کرتا ہے۔ بنیادی خلاصہ: {body} "
            "حوالہ جاتی دعووں کو ماخذ متن کے ساتھ ملا کر حتمی شکل دیں۔"
        )

    def _fit_word_target(self, body: str, target_words: int) -> str:
        words = body.split()
        if len(words) >= target_words:
            return " ".join(words[:target_words])
        filler = " This paragraph remains citation-ready and source-traceable."
        while len(body.split()) < target_words:
            body += filler
        return body

    def _standalone_generators(self, sections: dict[str, str]) -> dict[str, str]:
        intro = sections.get("Introduction") or next(iter(sections.values()), "")
        conclusion = sections.get("Conclusion") or list(sections.values())[-1]
        abstract = sections.get("Abstract") or intro
        related = sections.get("Related Work") or intro
        return {
            "abstract": abstract,
            "introduction": intro,
            "conclusion": conclusion,
            "related_work": related,
        }

    def _target_style_adaptation(self, payload: LiteratureReviewRequest) -> dict[str, str]:
        venue = payload.target_journal or payload.target_style.upper()
        return {
            "target": venue,
            "tone": payload.tone,
            "rule": f"Adapted headings, citation language, and submission framing for {venue}.",
            "mode": payload.mode,
        }

    def _paragraph_citation_map(self, sections: dict[str, str], source_spans: list[str]) -> list[dict[str, str]]:
        mapped = []
        fallback_span = source_spans[0] if source_spans else "No source span supplied."
        for section, content in sections.items():
            for index, paragraph in enumerate([part for part in content.split("\n") if part.strip()] or [content], start=1):
                mapped.append(
                    {
                        "section": section,
                        "paragraph_id": f"{section.lower().replace(' ', '-')}-{index}",
                        "citation_ready_text": f"{paragraph} [{index}]",
                        "source_span": source_spans[(index - 1) % len(source_spans)] if source_spans else fallback_span,
                    }
                )
        return mapped

    def _citation_style_previews(self, payload: LiteratureReviewRequest) -> dict[str, str]:
        title = payload.title
        return {
            "apa": f"Resora. (2026). {title}.",
            "ieee": f"[1] Resora, \"{title},\" 2026.",
            "mla": f"Resora. \"{title}.\" 2026.",
            "chicago": f"Resora. 2026. \"{title}.\"",
            "vancouver": f"1. Resora. {title}. 2026.",
        }

    def _reference_list(self, payload: LiteratureReviewRequest) -> list[str]:
        references = re.findall(r"([A-Z][A-Za-z]+ et al\.?,?\s+\d{4})", payload.extracted_text)
        if not references:
            references = [f"Resora Source Span {index + 1}. {payload.title}. 2026." for index in range(min(3, max(1, len(payload.extracted_text) // 80)))]
        return references[:20]

    def _source_spans(self, payload: LiteratureReviewRequest) -> list[str]:
        spans = [payload.extracted_text[:420]]
        spans.extend(figure.caption for figure in payload.figures[:3])
        spans.extend(table.caption for table in payload.tables[:2])
        return [span for span in spans if span]

    def _section_details(
        self,
        payload: LiteratureReviewRequest,
        sections: dict[str, str],
        source_spans: list[str],
        generated_at: str,
    ) -> list[LiteratureReviewSection]:
        details = []
        for title, content in sections.items():
            details.append(
                LiteratureReviewSection(
                    title=title,
                    content=content,
                    citation_style=payload.citation_style,
                    word_count=len(content.split()),
                    confidence_score=round(min(0.95, 0.61 + min(0.2, len(content.split()) / 500)), 2),
                    source_span=source_spans[:3],
                    model_used=self.provider.provider_name,
                    generated_at=generated_at,
                )
            )
        return details

    def _readability(self, text: str) -> float:
        words = max(1, len(text.split()))
        sentences = max(1, len(re.split(r"(?<=[.!?])\s+", text)))
        avg_sentence = words / sentences
        return round(max(0.0, 100 - avg_sentence * 1.8), 2)

    def _grammar_notes(self, text: str) -> list[str]:
        notes = []
        if "  " in text:
            notes.append("Double-spacing normalized")
        if len(text.split()) > 1200:
            notes.append("Long paragraphs should be broken for readability")
        notes.append("Formal tense consistency should be checked before submission")
        return notes

    def _academic_style_corrections(self, payload: LiteratureReviewRequest) -> list[str]:
        corrections = ["Prefer evidence-linked claims over broad generalizations."]
        if payload.tone == "concise":
            corrections.append("Condense long setup clauses before reporting findings.")
        if payload.target_journal:
            corrections.append(f"Align terminology with {payload.target_journal} author guidelines.")
        return corrections

    def _transition_suggestions(self, sections: dict[str, str]) -> list[str]:
        keys = list(sections)
        return [f"Add a bridging sentence between {keys[index]} and {keys[index + 1]}." for index in range(max(0, len(keys) - 1))][:5]

    def _citation_diversity_nudge(self, text: str) -> str:
        return "Consider balancing seminal papers with recent preprints and cross-domain evidence."

    def _inserted_visuals(self, payload: LiteratureReviewRequest) -> list[str]:
        visuals = [figure.caption for figure in payload.figures[:4]]
        visuals.extend(table.caption for table in payload.tables[:3])
        return visuals

    def _figure_table_insertions(self, payload: LiteratureReviewRequest) -> list[dict[str, str]]:
        insertions = []
        for figure in payload.figures[:4]:
            insertions.append({"type": "figure", "id": figure.figure_id, "caption": figure.caption, "placement": "Comparative Findings"})
        for table in payload.tables[:3]:
            insertions.append({"type": "table", "id": table.table_id, "caption": table.caption, "placement": "Datasets and Benchmarks"})
        return insertions

    def _exports(self, payload: LiteratureReviewRequest, sections: dict[str, str]) -> dict[str, str]:
        body = "\n\n".join(f"{title}\n{content}" for title, content in sections.items())
        latex_body = "\n".join(f"\\section*{{{title}}}\n{content}" for title, content in sections.items())
        references = "\n".join(f"\\item {item}" for item in self._reference_list(payload))
        return {
            "markdown": body,
            "latex": latex_body,
            "overleaf_latex": "\\documentclass{article}\n\\begin{document}\n" + latex_body + "\n\\begin{thebibliography}{9}\n" + references + "\n\\end{thebibliography}\n\\end{document}",
            "docx": f"DOCX-ready package manifest for {payload.title}: headings, citations, comments, and references embedded.",
            "pdf": f"PDF-ready package manifest for {payload.title}: generated from LaTeX export with citation style {payload.citation_style}.",
            "bibtex": "\n".join(f"@article{{resora{index}, title={{{ref}}}, year={{2026}}}}" for index, ref in enumerate(self._reference_list(payload), start=1)),
            "endnote": "\n".join(f"%0 Journal Article\n%T {ref}\n%D 2026\n" for ref in self._reference_list(payload)),
            "ris": "\n".join(f"TY  - JOUR\nTI  - {ref}\nPY  - 2026\nER  -\n" for ref in self._reference_list(payload)),
        }

    def _export_artifacts(self, payload: LiteratureReviewRequest, exports: dict[str, str], generated_at: str) -> list[ExportArtifact]:
        packaged = {artifact.format: artifact for artifact in self.packager.package(payload.title, exports)}
        return [
            ExportArtifact(
                format=name,
                file_name=f"{payload.title.lower().replace(' ', '-')}.{self._extension_for(name)}",
                content=content,
                citation_style=payload.citation_style,
                generated_at=generated_at,
                storage_uri=packaged[name].storage_uri if name in packaged else None,
                content_type=packaged[name].content_type if name in packaged else None,
                byte_size=packaged[name].byte_size if name in packaged else 0,
            )
            for name, content in exports.items()
        ]

    def _extension_for(self, format_name: str) -> str:
        mapping = {"markdown": "md", "latex": "tex", "overleaf_latex": "tex", "docx": "docx", "pdf": "pdf", "bibtex": "bib", "endnote": "enw", "ris": "ris"}
        return mapping.get(format_name, "txt")

    def _cover_letter(self, payload: LiteratureReviewRequest) -> str:
        return f"Dear Editor, we submit {payload.title} for consideration. This manuscript synthesizes current evidence with transparent AI-assisted drafting."

    def _peer_review_response(self, payload: LiteratureReviewRequest) -> str:
        return f"We thank the reviewers for their feedback on {payload.title}. We revised clarity, evidence linkage, and section transitions."

    def _version_history(self, payload: LiteratureReviewRequest) -> list[dict[str, str]]:
        return [
            {"version": "v1", "note": "Initial structured draft"},
            {"version": "v2", "note": "Self-critique and style adaptation applied"},
            {"version": f"v3-{uuid4().hex[:4]}", "note": "Export-ready package generated"},
        ]

    def _rollback_preview(self, payload: LiteratureReviewRequest, versions: list[dict[str, str]]) -> dict[str, str] | None:
        if not payload.rollback_to_version:
            return None
        match = next((version for version in versions if version["version"] == payload.rollback_to_version), None)
        return match or {"version": payload.rollback_to_version, "note": "Requested rollback target not found; keep latest draft."}

    def _track_changes(self, sections: dict[str, str]) -> list[dict[str, str]]:
        return [
            {"section": key, "change": "Section refined for clarity and evidence traceability"}
            for key in list(sections)[:5]
        ]

    def _plagiarism_report(self, payload: LiteratureReviewRequest, sections: dict[str, str]) -> dict[str, float | str | list[str]]:
        draft = " ".join(sections.values()).lower()
        source = payload.extracted_text.lower()
        draft_terms = set(re.findall(r"\w{5,}", draft))
        source_terms = set(re.findall(r"\w{5,}", source))
        overlap = len(draft_terms & source_terms) / max(1, len(draft_terms))
        return {
            "self_similarity_score": round(overlap, 2),
            "plagiarism_risk": "low" if overlap < 0.65 else "review-needed",
            "matched_terms": sorted(list(draft_terms & source_terms))[:12],
        }

    def _word_count_report(self, payload: LiteratureReviewRequest, sections: dict[str, str]) -> dict[str, int | str]:
        actual = sum(len(content.split()) for content in sections.values())
        return {
            "target": payload.word_count_target,
            "actual": actual,
            "status": "within-target" if actual <= payload.word_count_target else "over-target",
        }

    def _section_regeneration(self, payload: LiteratureReviewRequest, sections: dict[str, str]) -> dict[str, str]:
        if not payload.section_only:
            return {"status": "not-requested", "instruction": payload.regenerate_instruction or ""}
        current = sections.get(payload.section_only, "")
        return {
            "status": "ready",
            "section": payload.section_only,
            "instruction": payload.regenerate_instruction or "Regenerate this section with the same evidence.",
            "regenerated_preview": current,
        }

    def _confidence_score(
        self,
        critique: dict[str, list[str]],
        payload: LiteratureReviewRequest,
        sections: dict[str, str],
    ) -> float:
        total_claims = len(critique["supported_claims"]) + len(critique["unsupported_claims"])
        support_ratio = len(critique["supported_claims"]) / total_claims if total_claims else 0.5
        structure_bonus = min(0.15, len(sections) / 100)
        visual_bonus = 0.05 if payload.figures or payload.tables else 0.0
        return round(min(0.96, 0.55 + support_ratio * 0.25 + structure_bonus + visual_bonus), 2)
