export type SearchCopyKey = keyof typeof searchCopyEn;
export type SearchCopy = Partial<Record<SearchCopyKey, string>>;
export type SearchT = (key: SearchCopyKey, values?: Record<string, string | number>) => string;

const loaders = import.meta.glob<SearchCopy>("../../i18n/search-copy/*.json", { import: "default" });
const apiBaseUrl = import.meta.env.VITE_API_BASE_URL || "http://127.0.0.1:8000/api/v1";
const NEVER_TRANSLATED = new Set<SearchCopyKey>(["exampleDoi", "yearRange", "cmpExportCsv", "cmpExportMarkdownShort", "cmpExportJsonShort", "cmpExportXlsx", "cmpDoiLabel"]);

/** Short fingerprint of the English source: a cached fill is reused only while the English text is unchanged. */
const SOURCE_VERSION = (() => {
  let hash = 5381;
  const text = JSON.stringify(searchCopyEn);
  for (let index = 0; index < text.length; index += 1) hash = ((hash << 5) + hash + text.charCodeAt(index)) | 0;
  return (hash >>> 0).toString(36);
})();

/** A language is selectable when its catalog file exists; any label still missing is filled by the API. */
export function hasSearchCatalog(code: string) {
  return code === "en" || Object.keys(loaders).some((path) => path.endsWith(`/search-copy/${code}.json`));
}

export function fillTemplate(template: string, values: Record<string, string | number>) {
  return template.replace(/\{(\w+)\}/g, (match, key: string) => (key in values ? String(values[key]) : match));
}

function samePlaceholders(candidate: string, english: string) {
  const names = (value: string) => [...value.matchAll(/\{(\w+)\}/g)].map((match) => match[1]).sort().join(",");
  return names(candidate) === names(english);
}

/** True when a translated label can be shown: present, same placeholders, not an untranslated copy, no engine junk. */
function usable(key: SearchCopyKey, value: unknown): value is string {
  if (typeof value !== "string" || !value.trim()) return false;
  const english: string = searchCopyEn[key];
  if (!samePlaceholders(value, english)) return false;
  if (value.includes("→") && !english.includes("→")) return false;
  if (value === english && !NEVER_TRANSLATED.has(key) && /[A-Za-z]{3}/.test(english.replace(/Resora|BibTeX|DOI|APA|CSV|\{\w+\}/g, ""))) return false;
  return true;
}

function clean(catalog: Record<string, unknown> | null | undefined): SearchCopy {
  const result: SearchCopy = {};
  if (!catalog) return result;
  (Object.keys(searchCopyEn) as SearchCopyKey[]).forEach((key) => {
    if (usable(key, catalog[key])) result[key] = catalog[key] as string;
  });
  return result;
}

function missingKeys(copy: SearchCopy) {
  return (Object.keys(searchCopyEn) as SearchCopyKey[]).filter((key) => !NEVER_TRANSLATED.has(key) && !copy[key]);
}

const fillCacheKey = (language: string) => `resora-search-copy:${language}:${SOURCE_VERSION}`;

function readFill(language: string): SearchCopy {
  try {
    const raw = window.localStorage.getItem(fillCacheKey(language));
    return raw ? clean(JSON.parse(raw) as Record<string, unknown>) : {};
  } catch {
    return {};
  }
}

function writeFill(language: string, copy: SearchCopy) {
  try {
    window.localStorage.setItem(fillCacheKey(language), JSON.stringify(copy));
  } catch {
    /* storage full or blocked — the fill is simply requested again next time */
  }
}

const pendingFills = new Map<string, Promise<SearchCopy>>();

/** Ask the API for this language's complete catalog (translated once on the server, then cached for everyone). */
function fetchFill(language: string): Promise<SearchCopy> {
  const existing = pendingFills.get(language);
  if (existing) return existing;
  const request = fetch(`${apiBaseUrl}/search/ui-copy/${encodeURIComponent(language)}`)
    .then((response) => (response.ok ? response.json() : null))
    .then((data: { messages?: Record<string, unknown> } | null) => clean(data?.messages))
    .catch(() => ({} as SearchCopy))
    .finally(() => pendingFills.delete(language));
  pendingFills.set(language, request);
  return request;
}

/**
 * Translated Search copy for `language`. Order of preference for every label:
 * shipped catalog → API fill (cached in this browser) → English, and English only while the fill is loading.
 */
export function useSearchCopy(language: string): SearchT {
  const [copy, setCopy] = useState<SearchCopy>({});
  useEffect(() => {
    let active = true;
    if (language === "en") {
      setCopy({});
      return () => {
        active = false;
      };
    }
    const cachedFill = readFill(language);
    setCopy(cachedFill);
    const loader = Object.entries(loaders).find(([path]) => path.endsWith(`/search-copy/${language}.json`))?.[1];
    void (async () => {
      let shipped: SearchCopy = {};
      try {
        shipped = loader ? clean((await loader()) as Record<string, unknown>) : {};
      } catch {
        shipped = {};
      }
      let merged: SearchCopy = { ...cachedFill, ...shipped };
      if (active) setCopy(merged);
      if (!missingKeys(merged).length) return;
      const fill = await fetchFill(language);
      if (!active) return;
      const filled: SearchCopy = {};
      missingKeys(merged).forEach((key) => {
        if (fill[key]) filled[key] = fill[key];
      });
      if (Object.keys(filled).length) {
        writeFill(language, { ...cachedFill, ...filled });
        merged = { ...merged, ...filled };
        setCopy(merged);
      }
    })();
    return () => {
      active = false;
    };
  }, [language]);
  return useCallback<SearchT>((key, values) => {
    const template = copy[key] || searchCopyEn[key];
    return values ? fillTemplate(template, values) : template;
  }, [copy]);
}
